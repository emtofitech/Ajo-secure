/* ═══════════════════════════════════════════════════════════
   FLOATING MONEY
   Entrance lives on the inner wrapper, the endless drift on the
   <img>, and parallax on the outer box — three separate elements
   so no two of them ever animate `transform` at once.
   ═══════════════════════════════════════════════════════════ */
function FloatingMoney() {
  const layerRef = useRef(null);

  useEffect(() => {
    const layer = layerRef.current;
    if (!layer) return;
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    if (!window.matchMedia("(min-width: 768px)").matches) return;

    const boxes = Array.from(layer.querySelectorAll("[data-depth]"));

    let raf = 0;
    let targetX = 0;
    let targetY = 0;
    let curX = 0;
    let curY = 0;

    const tick = () => {
      curX += (targetX - curX) * 0.08;
      curY += (targetY - curY) * 0.08;

      for (const box of boxes) {
        const depth = Number(box.dataset.depth) || 0;
        box.style.setProperty("--px", `${(curX * depth * 18).toFixed(2)}px`);
        box.style.setProperty("--py", `${(curY * depth * 18).toFixed(2)}px`);
      }

      if (Math.abs(targetX - curX) > 0.001 || Math.abs(targetY - curY) > 0.001) {
        raf = requestAnimationFrame(tick);
      } else {
        raf = 0;
      }
    };

    const onMove = (e) => {
      targetX = (e.clientX / window.innerWidth - 0.5) * 2;
      targetY = (e.clientY / window.innerHeight - 0.5) * 2;
      if (!raf) raf = requestAnimationFrame(tick);
    };

    window.addEventListener("mousemove", onMove, { passive: true });
    return () => {
      window.removeEventListener("mousemove", onMove);
      if (raf) cancelAnimationFrame(raf);
    };
  }, []);

  return (
    <div
      ref={layerRef}
      className="absolute inset-0 pointer-events-none overflow-hidden"
      aria-hidden="true"
    >
      {MONEY.map((m, i) => (
        <div
          key={i}
          data-depth={m.depth}
          className={`absolute money-parallax ${m.pos} ${m.w} ${m.ar} ${m.blur} ${
            m.hideSm ? "hidden sm:block" : ""
          }`}
        >
          <div className="absolute inset-0 anim-scale-in" style={{ animationDelay: `${m.enter}ms` }}>
            <img
              src={m.src}
              alt=""
              aria-hidden="true"
              draggable={false}
              className={`money-float ${m.loop} w-full h-full object-contain`}
              style={{
                opacity: m.opacity,
                "--dur": m.dur,
                "--dx": m.dx,
                "--dy": m.dy,
                "--r0": m.r0,
                "--r1": m.r1,
                animationDelay: m.ad,
              }}
            />
          </div>
        </div>
      ))}
    </div>
  );
}

